CAPTURED_FILE = 'neis-screens.json'
_captured_cache: dict | None = None


def _resource_dir() -> Path:
    bundled = getattr(sys, '_MEIPASS', None)
    if bundled:
        return Path(bundled) / 'resources'
    return Path(__file__).resolve().parents[1] / 'resources'


def captured() -> dict:
    """{화면 이름: 걷어 온 자료}. 파일이 없으면 빈 사전 — 손으로 쓴 설명만으로 돈다."""
    global _captured_cache
    if _captured_cache is None:
        try:
            rows = json.loads((_resource_dir() / CAPTURED_FILE).read_text(encoding='utf-8'))
        except (OSError, ValueError):
            rows = []
        _captured_cache = {row['name']: row for row in rows if row.get('name')}
    return _captured_cache


def inner_tabs(name: str) -> tuple[str, ...]:
    """화면 안쪽 하위 탭. 열고 나서 한 번 더 눌러야 하는 자리들.

    두 군데에서 모은다. **정본**(업무분장 메뉴목록)에는 담임이 쓸 수 있는 안쪽 탭이 빠짐없이
    적혀 있고, **화면 수집**에는 화면을 실제로 열어 본 그대로가 남는다. 정본에 없는 탭
    (부서장만 쓰는 것)도 화면에는 보이므로 둘을 합쳐야 말을 다 알아듣는다.
    """
    from . import neis_roles
    # 화면에서 본 차례가 먼저다 — 실제로 눌러야 하는 순서이기 때문이다.
    out = list(captured().get(name, {}).get('tabs') or ())
    for tab in neis_roles.inner_tabs(name):
        if tab not in out:
            out.append(tab)
    return tuple(out)


def content_words(name: str, limit: int = 120) -> tuple[str, ...]:
    """화면 안에 실제로 있는 낱말. 이름에도 설명에도 없는 말을 받아 내는 데 쓴다."""
    row = captured().get(name)
    if not row:
        return ()
    out, seen = [], set()
    for key in ('tabs', 'fields', 'actions', 'columns', 'text'):
        for value in row.get(key) or []:
            text = str(value).replace('필수입력', '').strip()
            if len(text) < 2 or text in seen:
                continue
            seen.add(text)
            out.append(text)
            if len(out) >= limit:
                return tuple(out)
    return tuple(out)


